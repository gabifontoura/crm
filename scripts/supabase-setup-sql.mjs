// Joins every migration in supabase/migrations (in order) into supabase/setup.sql,
// so a new Supabase project is set up by pasting one file in the SQL Editor.
// Run with: npm run db:setup-sql
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const parts = files.map((f) => `-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf-8").trim()}\n`);
const header = `-- CRM database: every migration in order (${files.length} files), generated by
-- scripts/supabase-setup-sql.mjs. Paste it in Supabase › SQL Editor and click Run.
-- Safe to run again: each step checks what already exists.\n\n`;
writeFileSync("supabase/setup.sql", header + parts.join("\n"));
console.log(`supabase/setup.sql: ${files.length} migrations`);
